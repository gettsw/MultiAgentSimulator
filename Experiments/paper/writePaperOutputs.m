function files = writePaperOutputs(outDir, S)
% Writes the regenerated numbers for the paper into outDir:
%   runs.csv            every run of every experiment (one row per run)
%   comparison.csv      draft values next to the regenerated ones (if S.comparison is given)
%   table1_parameters.tex ... table4_battery.tex   tabular environments to \input in the paper
%   macros.tex          \newcommand values quoted in the text (prefix \pr)
% S has fields parameters (paperTables("parameters", ...)) and policy, planner, battery
% (paperRuns outputs), and optionally comparison (paperComparison).
if ~isfolder(outDir), mkdir(outDir); end
files = fullfile(outDir, ["runs.csv", "table1_parameters.tex", "table2_policy.tex", ...
    "table3_planner.tex", "table4_battery.tex", "macros.tex"]);

runs = [addvars(S.policy.Runs, repmat("policy", height(S.policy.Runs), 1), 'Before', 1, 'NewVariableNames', 'Experiment'); ...
        addvars(S.planner.Runs, repmat("planner", height(S.planner.Runs), 1), 'Before', 1, 'NewVariableNames', 'Experiment'); ...
        addvars(S.battery.Runs, repmat("battery", height(S.battery.Runs), 1), 'Before', 1, 'NewVariableNames', 'Experiment')];
writetable(runs, files(1));
if isfield(S, 'comparison') && ~isempty(S.comparison)
    files(end+1) = fullfile(outDir, "comparison.csv");
    writetable(S.comparison, files(end));
end

P = S.parameters;
writeLines(files(2), tabular("|l|c|c|", ["Parameter", "Symbol", "Value"], ...
    [P.Parameter, arrayfun(@texSymbol, P.Symbol), arrayfun(@texValue, P.Value)]));

T2 = paperTables("policy", S.policy);
nS = numel(S.policy.Seeds);
cells = [T2.Policy, compose("%.1f", T2{:, 2:nS+1}), boldBest(T2.Mean, "%.1f", @min), compose("%.2f", T2.StdOverMean)];
writeLines(files(3), tabular("|l|" + join(repmat("c|", 1, nS + 2), ""), ...
    ["Policy", "R" + (1:nS), "Mean", "Std/Mean (\%)"], cells));

T3 = paperTables("planner", S.planner);
k = 1:height(T3) - 1;   % planner rows; the last row is the change
cells = [T3.Condition(k), boldBest(T3.J(k), "%.1f", @min), boldBest(T3.L(k), "%.0f", @min), ...
         boldBest(T3.Theta(k), "%.0f", @min), boldBest(T3.Ea(k), "%.0f", @min); ...
         "Change (\%)", compose("%+.2f", T3{end, ["J", "L", "Theta", "Ea"]})];
writeLines(files(4), tabular("|l|c|c|c|c|", ...
    ["Planner", "$J(T)$", "$L$ (m)", "$\Theta$ (rad)", "$E_a$ (m\textsuperscript{2}/s\textsuperscript{3})"], cells));

T4 = paperTables("battery", S.battery);
k = 1:height(T4) - 1;
change = [""; compose("%+.2f", T4.Energy(end))];
cells = [T4.Condition(k), boldBest(T4.SOC(k), "%.1f", @max), boldBest(T4.Energy(k), "%.0f", @min), change];
writeLines(files(5), tabular("|l|c|c|c|", ["Planner", "SOC (\%)", "Energy (J)", "Change (\%)"], cells));

macros = [ ...
    macro("prRuns", sprintf('%d', nS))
    macro("prJRandomWalk", sprintf('%.1f', T2.Mean(1)))
    macro("prJBatteryEfficient", sprintf('%.1f', T2.Mean(2)))
    macro("prSpreadRandomWalk", sprintf('%.2f', T2.StdOverMean(1)))
    macro("prSpreadBatteryEfficient", sprintf('%.2f', T2.StdOverMean(2)))
    macro("prPolicyReduction", sprintf('%.1f', 100 * (T2.Mean(1) - T2.Mean(2)) / T2.Mean(1)))
    macro("prPlannerChangeJ", sprintf('%+.2f', T3.J(end)))
    macro("prPlannerChangeL", sprintf('%+.2f', T3.L(end)))
    macro("prPlannerChangeTheta", sprintf('%+.2f', T3.Theta(end)))
    macro("prPlannerChangeEa", sprintf('%+.2f', T3.Ea(end)))
    macro("prSOCDijkstra", sprintf('%.1f', T4.SOC(1)))
    macro("prSOCEnergyEfficient", sprintf('%.1f', T4.SOC(2)))
    macro("prEnergyChange", sprintf('%+.2f', T4.Energy(end)))];
writeLines(files(6), ["% Values regenerated by PaperResults.mlx; do not edit by hand"; macros]);
end

function lines = tabular(spec, header, cells)
lines = ["\begin{tabular}{" + spec + "}"; "\hline"; join(header, " & ") + " \\"; "\hline"; ...
         join(cells, " & ", 2) + " \\"; "\hline"; "\end{tabular}"];
end

function s = boldBest(x, fmt, pick)
% Formatted values with the best one (pick = @min or @max) in bold
s = compose(fmt, x);
[~, i] = pick(x);
s(i) = "\textbf{" + s(i) + "}";
end

function m = macro(name, value)
m = "\newcommand{\" + name + "}{" + value + "}";
end

function s = texSymbol(sym)
map = dictionary(["T", "dt", "A_i", "B_i", "R_i(0)", "v_max", "a_max", "K_p, K_d", "kappa", ...
                  "tau_dwell", "P_0, alpha, gamma", "P_cpu", "P_comp", "eta_conv", "Q"], ...
    ["$T$", "$\Delta t$", "$A_i$", "$B_i$", "$R_i(0)$", "$v_{\max}$", "$a_{\max}$", "$K_p$, $K_d$", ...
     "$\kappa$", "$\tau_{\mathrm{dwell}}$", "$P_0$, $\alpha$, $\gamma$", "$P_{cpu}$", "$P_{comp}$", ...
     "$\eta_{conv}$", "$Q$"]);
if sym == "", s = "--"; elseif isKey(map, sym), s = map(sym); else, s = sym; end
end

function s = texValue(v)
s = replace(v, ["%", "m/s^2", "U("], ["\%", "m/s\textsuperscript{2}", "$\mathcal{U}$("]);
end

function writeLines(file, lines)
writelines(lines, file);
end
